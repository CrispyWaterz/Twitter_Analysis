import seaborn as sns

if 'padded_sequences_combined_for_prediction' in locals() and padded_sequences_combined_for_prediction.size > 0 and 'combined_df' in locals() and not combined_df.empty:
    print("\nMaking sentiment predictions on combined_df using the hybrid model...")
    hybrid_predictions = hybrid_model.predict(padded_sequences_combined_for_prediction)

    # Get the predicted class (0, 1, or 2) by taking the argmax of the probabilities
    combined_df['predicted_sentiment'] = np.argmax(hybrid_predictions, axis=1)

    print("Sentiment prediction complete. Added 'predicted_sentiment' column to combined_df.")

    # Display the first few rows with the new predicted sentiment
    print("\nFirst 10 rows of combined_df with predicted sentiments:")
    display(combined_df[['full_text', 'processed_text', 'predicted_sentiment']].head(10))

    # Display the distribution of predicted sentiments
    print("\nDistribution of Predicted Sentiments in Scraped Data:")
    sentiment_labels_map = {0: 'Negative', 1: 'Neutral', 2: 'Positive'}
    predicted_sentiment_counts = combined_df['predicted_sentiment'].map(sentiment_labels_map).value_counts().sort_index()
    print(predicted_sentiment_counts)

    # Plot the distribution
    plt.figure(figsize=(8, 6))
    sns.barplot(x=predicted_sentiment_counts.index, y=predicted_sentiment_counts.values, palette='viridis', hue=predicted_sentiment_counts.index, legend=False)
    plt.title('Distribution of Predicted Sentiments in Scraped Data')
    plt.xlabel('Predicted Sentiment (0: Negative, 1: Neutral, 2: Positive)')
    plt.ylabel('Count')
    plt.xticks(ticks=[0, 1, 2], labels=['Negative', 'Neutral', 'Positive'])
    plt.grid(axis='y', linestyle='--', alpha=0.7)
    plt.show()
