"""## 3. Build LSTM-CNN Hybrid Model

Here, we define a hybrid deep learning model that combines both Long Short-Term Memory (LSTM) and Convolutional Neural Network (CNN) layers. LSTMs are effective at capturing long-range dependencies in sequential data (like text), while CNNs are good at extracting local features (like n-grams). The model will use an embedding layer to represent words as dense vectors, followed by convolutional and LSTM layers, and finally a dense output layer for sentiment classification.
"""

import tensorflow as tf
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Embedding, Conv1D, GlobalMaxPooling1D, LSTM, Dense, Dropout, Bidirectional

if 'VOCAB_SIZE_LABELED' not in locals():
    VOCAB_SIZE_LABELED = MAX_VOCAB_SIZE + 1 # Fallback if not defined from labeled data processing

# Build the LSTM-CNN Hybrid model
print("Building LSTM-CNN Hybrid Model...")
hybrid_model = Sequential([
    Embedding(VOCAB_SIZE_LABELED, EMBEDDING_DIM, input_length=MAX_SEQUENCE_LENGTH, name="embedding_layer"),

    # CNN Part: Capture local features. Output is 3D (batch, timesteps, filters).
    Conv1D(filters=128, kernel_size=5, activation='relu', name="conv1d_layer"),
    # The GlobalMaxPooling1D layer is intentionally removed here to keep the output 3D
    # so it can be fed directly into the Bidirectional LSTM layer.

    # Dropout for regularization before LSTM
    Dropout(0.3, name="dropout_cnn"),

    # LSTM Part: Capture sequential dependencies. Expects 3D input.
    # Using Bidirectional LSTM for better context understanding
    Bidirectional(LSTM(64, return_sequences=False), name="bidirectional_lstm_layer"),
    Dropout(0.5, name="dropout_lstm"),

    # Output layer for 3 classes (negative, neutral, positive)
    Dense(3, activation='softmax', name="output_layer")
])

# Compile the model
hybrid_model.compile(optimizer='adam', loss='sparse_categorical_crossentropy', metrics=['accuracy'])

print("LSTM-CNN Hybrid Model Built and Compiled.")
hybrid_model.summary()

"""## 4.1 Hyperparameter Tuning with Keras Tuner

To further optimize our model, we'll use Keras Tuner to systematically search for the best combination of hyperparameters, such as the number of filters in `Conv1D` layers, units in `LSTM` layers, and dropout rates. This will help us find a model configuration that potentially yields better performance.
"""

import keras_tuner

# Define the model building function for Keras Tuner
def build_tunable_model(hp):
    model = Sequential([
        Embedding(VOCAB_SIZE_LABELED, EMBEDDING_DIM, input_length=MAX_SEQUENCE_LENGTH, name="embedding_layer"),

        # Tunable Conv1D Layer
        Conv1D(
            filters=hp.Int('filters', min_value=64, max_value=256, step=64),
            kernel_size=5, activation='relu', name="conv1d_layer"
        ),
        Dropout(hp.Float('dropout_cnn', min_value=0.2, max_value=0.5, step=0.1), name="dropout_cnn"),

        # Tunable Bidirectional LSTM Layer
        Bidirectional(LSTM(hp.Int('lstm_units', min_value=32, max_value=128, step=32), return_sequences=False), name="bidirectional_lstm_layer"),
        Dropout(hp.Float('dropout_lstm', min_value=0.3, max_value=0.6, step=0.1), name="dropout_lstm"),

        # Output layer
        Dense(3, activation='softmax', name="output_layer")
    ])

    # Tunable learning rate for the Adam optimizer
    learning_rate = hp.Choice('learning_rate', values=[1e-2, 1e-3, 1e-4])
    optimizer = tf.keras.optimizers.Adam(learning_rate=learning_rate)

    model.compile(optimizer=optimizer, loss='sparse_categorical_crossentropy', metrics=['accuracy'])
    return model

print("Tunable model building function defined.")

# Initialize the Keras Tuner (RandomSearch in this case)
tuner = keras_tuner.RandomSearch(
    build_tunable_model,
    objective='val_accuracy',
    max_trials=5,  # Number of different hyperparameter combinations to try
    executions_per_trial=1, # Number of models to train for each trial (for robustness)
    directory='keras_tuner_dir', # Directory to store results
    project_name='sentiment_hybrid_tuning'
)

print("Keras Tuner initialized. Starting search for best hyperparameters...")

# Run the hyperparameter search
# Use a small number of epochs for tuning to speed up the process
tuner.search(X_train_labeled, y_train_labeled, epochs=3, validation_split=0.2, verbose=1)

print("Hyperparameter search complete.")

# Get the optimal hyperparameters
best_hps = tuner.get_best_hyperparameters(num_trials=1)[0]
print(f"\nOptimal hyperparameters found:")
print(f"  Conv1D filters: {best_hps.get('filters')}")
print(f"  LSTM units: {best_hps.get('lstm_units')}")
print(f"  CNN dropout rate: {best_hps.get('dropout_cnn')}")
print(f"  LSTM dropout rate: {best_hps.get('dropout_lstm')}")
print(f"  Learning rate: {best_hps.get('learning_rate')}")

# Build the best model found by the tuner and assign it to hybrid_model
hybrid_model = tuner.get_best_models(num_models=1)[0]
